import { sheetApi } from '../bridge/sheet';
import type { SheetDriver } from './selfTest';
import type { StyleDTO } from '../bridge/sheet';

export async function borderDialogSelfTest(sheet: SheetDriver, sheetIndex: number): Promise<string> {
  const lines = ['\n## 框線編輯與預覽', '', '| | 項目 |', '| --- | --- |'];
  let passed = 0, total = 0;
  const expect = (name: string, ok: boolean, detail = '') => { total++; if (ok) passed++; lines.push(`| ${ok ? '✅' : '❌'} | ${name}${ok || !detail ? '' : `：${detail.replaceAll('|', '/')}`} |`); };
  const step = async () => { await sheet.whenIdle(); await new Promise(r => setTimeout(r, 100)); };
  const modal = () => document.querySelector<HTMLElement>('[role="dialog"][aria-label="儲存格格式"]')!;
  const button = (text: string) => Array.from(modal().querySelectorAll<HTMLButtonElement>('button')).find(b => b.textContent?.trim() === text)!;
  const open = async () => { sheet.focus(); sheet.pressKey('1', { metaKey: true }); await step(); button('框線').click(); await step(); };
  const read = async (r: number, c: number): Promise<StyleDTO | undefined> => {
    const data = await sheetApi.getBlocks(sheetIndex, [{ row: Math.floor(r / 64), col: Math.floor(c / 32) }], 0);
    const cell = data.blocks?.[0]?.cells?.find(cell => cell.r === r % 64 && cell.c === c % 32);
    return data.styles?.find(st => st.id === (cell?.st ?? 0));
  };
  const pickColor = async (color: string) => {
    Array.from(modal().querySelectorAll<HTMLButtonElement>('button')).find(b => b.textContent?.includes('線條顏色'))!.click();
    await step();
    modal().querySelector<HTMLButtonElement>(`[aria-label="#${color}"]`)!.click(); await step();
  };
  const brush = async (style: string, color: string) => {
    const select = modal().querySelector<HTMLSelectElement>('select')!;
    select.value = style; select.dispatchEvent(new Event('change', { bubbles: true }));
    await pickColor(color);
  };
  const clickEdge = async (edge: string) => {
    modal().querySelector<SVGGElement>(`g[aria-label="切換${edge}"]`)!.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    await step();
  };
  const select = async (r0: number, c0: number, r1: number, c1: number) => {
    await sheet.goToName(`${String.fromCharCode(65 + c0)}${r0 + 1}`);
    sheet.setSelectionForTest({ active: { row: r0, col: c0 }, anchor: { row: r0, col: c0 }, focus: { row: r1, col: c1 }, ranges: [{ r0, c0, r1, c1 }] });
    await step();
  };
  await select(54, 1, 56, 3);
  await sheet.applyFormat({ border: 'none' });
  await sheet.applyFormat({ border: 'top', borderColor: '00FF00' });
  await step();
  await open();
  expect('開啟視窗預覽既有框線', modal().querySelector('g[aria-label="切換上框線"] line[stroke="#00FF00"]') !== null, modal().querySelector('g[aria-label="切換上框線"]')?.outerHTML);
  expect('框線分頁提供十三種線型', modal().querySelector('select')?.options.length === 13);
  await brush('double', 'FF0000'); button('外框線').click(); await step();
  expect('雙線外框預覽使用選定色彩', modal().querySelectorAll('.border-preview line[stroke="#FF0000"]').length === 8);
  await brush('dotted', '0070C0'); button('內框線').click(); await step();
  expect('內框可使用不同線型與色彩', modal().querySelectorAll('.border-preview line[stroke="#0070C0"][stroke-dasharray="1 1"]').length === 2);
  expect('預覽編輯尚未寫入文件', (await read(54, 1))?.top.color === '00FF00' && !(await read(54, 1))?.bottom.style);
  await brush('double', 'FF0000');
  await clickEdge('上框線');
  expect('點選預覽可清除指定邊線', modal().querySelector('g[aria-label="切換上框線"]')?.getAttribute('aria-pressed') === 'false');
  await clickEdge('上框線');
  expect('第三狀態保留原框線並預覽原色', modal().querySelector('g[aria-label="切換上框線"]')?.getAttribute('aria-pressed') === 'mixed' && modal().querySelector('g[aria-label="切換上框線"] line[stroke="#00FF00"]') !== null, modal().querySelector('g[aria-label="切換上框線"]')?.outerHTML);
  const topEdge = modal().querySelector<SVGGElement>('g[aria-label="切換上框線"]')!;
  topEdge.focus();
  topEdge.dispatchEvent(new KeyboardEvent('keydown', { key: ' ', bubbles: true, cancelable: true }));
  await step();
  expect('預覽可用空白鍵切換而不提交', topEdge.getAttribute('aria-pressed') === 'true' && !!modal());
  button('確定').click(); await step();
  const corner = await read(54, 1), center = await read(55, 2), neighbor = await read(53, 1);
  expect('多格範圍套用雙線外框與點線內框', corner?.top.style === 'double' && corner.left.color === 'FF0000' && center?.top.style === 'dotted' && center.right.color === '0070C0');
  expect('相鄰儲存格共用邊界同步', JSON.stringify(corner?.top) === JSON.stringify(neighbor?.bottom));
  await sheet.runMenu('undo'); await step();
  expect('框線設定一次復原', (await read(54, 1))?.top.color === '00FF00' && !(await read(55, 2))?.right.style);
  await sheet.runMenu('redo'); await step();
  expect('框線設定一次重做', (await read(54, 1))?.top.style === 'double' && (await read(55, 2))?.right.color === '0070C0');
  await open(); await clickEdge('左框線'); await clickEdge('左框線');
  button('確定').click(); await step();
  expect('清除左框線也清除鄰格右框線', !(await read(55, 1))?.left.style && !(await read(55, 0))?.right.style);
  expect('指定清除保留其餘邊線', (await read(56, 1))?.bottom.style === 'double' && (await read(55, 2))?.top.style === 'dotted');
  const beforeCancel = JSON.stringify(await read(54, 1));
  await open(); button('無框線').click(); await step(); button('取消').click(); await step();
  expect('取消框線草稿不修改文件', JSON.stringify(await read(54, 1)) === beforeCancel);
  await select(59, 1, 60, 2); await sheet.mergeCells(false); await step();
  await open();
  expect('單一合併儲存格停用內框控制', modal().querySelector<HTMLButtonElement>('[data-edge="insideH"]')?.disabled === true && modal().querySelector<HTMLButtonElement>('[data-edge="insideV"]')?.disabled === true);
  await brush('medium', 'FF0000'); button('外框線').click(); await step(); button('確定').click(); await step();
  const merged = await read(59, 1);
  expect('合併儲存格左上角保留完整外框', merged?.top.style === 'medium' && merged.bottom.style === 'medium' && merged.left.style === 'medium' && merged.right.style === 'medium');
  expect('合併儲存格底部與鄰格同步', (await read(60, 2))?.bottom.style === 'medium' && (await read(61, 2))?.top.style === 'medium');
  await select(65, 1, 65, 1);
  await sheetApi.format(sheetIndex,[{r0:65,c0:1,r1:65,c1:1}],{borders:{top:{style:'double',color:'FF0000'},bottom:{style:'dotted',color:'0070C0'}},diagonal:{style:'dashed',color:'0070C0'},diagonalDown:true});await step();
  const colorButton = () => Array.from(modal().querySelectorAll<HTMLButtonElement>('button')).find(b=>b.textContent?.includes('線條顏色'))!;
  await open();
  expect('既有不同框線色彩顯示混合而非自動',colorButton().textContent?.includes('混合')===true);
  await pickColor('00B050');
  expect('選色後立即顯示色碼與既有框線新色預覽',colorButton().textContent?.includes('#00B050')===true && modal().querySelector('.border-preview line[stroke="#00B050"]')!==null);
  button('確定').click();await step();
  let recolored=await read(65,1);
  expect('只選色確定也能改色並保留不同線型與斜線',recolored?.top.style==='double' && recolored.top.color==='00B050' && recolored.bottom.style==='dotted' && recolored.bottom.color==='00B050' && recolored.diagonal?.color==='00B050');
  expect('只改色同步相鄰共用邊界',(await read(64,1))?.bottom.color==='00B050' && (await read(66,1))?.top.color==='00B050');
  await open();expect('重新開啟顯示已儲存框線顏色',colorButton().textContent?.includes('#00B050')===true);button('取消').click();await step();
  await sheet.runMenu('undo');await step();expect('只改色一次復原保留原先不同顏色',(await read(65,1))?.top.color==='FF0000' && (await read(65,1))?.bottom.color==='0070C0');
  await sheet.runMenu('redo');await step();
  await open();colorButton().click();await step();button('自動').click();await step();button('確定').click();await step();
  recolored=await read(65,1);expect('可改回自動色並保留線型',recolored?.top.style==='double' && !recolored.top.color && recolored.bottom.style==='dotted' && !recolored.bottom.color);
  await open();await pickColor('FF0000');button('取消').click();await step();expect('取消只改色草稿不修改框線',!(await read(65,1))?.top.color);
  await select(69,1,70,2);await sheet.applyFormat({border:'none'});await step();
  await open();button('外框線').click();await step();
  await brush('double','FF0000');
  expect('先外框後改線型色彩立即更新雙線紅框預覽',modal().querySelectorAll('.border-preview line[stroke="#FF0000"]').length===8);
  button('確定').click();await step();
  expect('先外框後改設定可儲存雙線紅框',(await read(69,1))?.top.style==='double' && (await read(69,1))?.top.color==='FF0000' && (await read(70,2))?.right.style==='double');
  await open();expect('雙線紅框重新開啟保留線型與色彩',modal().querySelector<HTMLSelectElement>('select')?.value==='double' && colorButton().textContent?.includes('#FF0000')===true);button('取消').click();await step();
  await sheet.runMenu('undo');await step();expect('後改框線設定一次復原',!(await read(69,1))?.top.style);await sheet.runMenu('redo');await step();
  await open();
  const lineSelect=modal().querySelector<HTMLSelectElement>('select')!;lineSelect.value='thick';lineSelect.dispatchEvent(new Event('change',{bubbles:true}));await step();button('確定').click();await step();
  expect('既有框線只改線型生效且保留紅色',(await read(69,1))?.top.style==='thick' && (await read(69,1))?.top.color==='FF0000');
  await open();button('內框線').click();await step();await brush('dotted','0070C0');button('確定').click();await step();
  expect('先內框後選藍色點線不改外框',(await read(69,1))?.right.style==='dotted' && (await read(69,1))?.right.color==='0070C0' && (await read(69,1))?.top.style==='thick' && (await read(69,1))?.top.color==='FF0000');
  await select(73,1,73,1);await sheet.applyFormat({border:'none'});await step();await open();await clickEdge('上框線');await brush('mediumDashed','00B050');button('確定').click();await step();
  expect('先點個別邊線後改中虛線與綠色也會套用',(await read(73,1))?.top.style==='mediumDashed' && (await read(73,1))?.top.color==='00B050' && !(await read(73,1))?.bottom.style);
  await open();await brush('double','FF0000');button('重設變更').click();await step();button('確定').click();await step();
  expect('重設取消線型與顏色修改',(await read(73,1))?.top.style==='mediumDashed' && (await read(73,1))?.top.color==='00B050');
  lines.splice(2, 0, `- 結果：${passed} / ${total} 通過`, '');
  return lines.join('\n') + '\n';
}
